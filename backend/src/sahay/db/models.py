"""All ORM models for Sahay.

Single file by design — total schema is small enough to scan in one screen,
and cross-table FK relationships are easier to reason about co-located.

Multi-tenancy is enforced at the database layer via row-level security
(see infra/postgres-rls.sql). The `user_id` foreign key is the tenant key.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import TYPE_CHECKING
from uuid import UUID

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import CITEXT, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from sahay.db.base import Base, created_at, updated_at, uuid_pk

if TYPE_CHECKING:
    pass


# ─── Users + Auth ────────────────────────────────────────────────────


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid_pk]
    email: Mapped[str] = mapped_column(CITEXT, unique=True, nullable=False)
    email_verified: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    display_name: Mapped[str | None] = mapped_column(String(100))
    locale: Mapped[str] = mapped_column(String(8), default="en", nullable=False)
    tier: Mapped[str] = mapped_column(String(16), default="free", nullable=False)
    role: Mapped[str | None] = mapped_column(String(32))
    created_at: Mapped[created_at]
    last_active_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # Relationships (back-pop only where useful for cascades)
    refresh_tokens: Mapped[list["RefreshToken"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    app_grants: Mapped[list["UserAppGrant"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    action_logs: Mapped[list["ActionLog"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    files: Mapped[list["File"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    subscription: Mapped["Subscription | None"] = relationship(
        back_populates="user", uselist=False, cascade="all, delete-orphan"
    )

    __table_args__ = (
        CheckConstraint(
            "tier IN ('free', 'pro', 'power', 'enterprise')",
            name="tier_valid",
        ),
    )


class OtpChallenge(Base):
    """Short-lived OTP for email-based signup/login.

    Code is bcrypt-hashed. Lookup by (email, purpose) ordered by created_at desc
    to fetch latest unconsumed challenge.
    """

    __tablename__ = "otp_challenges"

    id: Mapped[uuid_pk]
    email: Mapped[str] = mapped_column(CITEXT, nullable=False)
    code_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    purpose: Mapped[str] = mapped_column(String(16), nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    attempts: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    consumed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    requested_ip: Mapped[str | None] = mapped_column(String(45))   # IPv6 fits
    created_at: Mapped[created_at]

    __table_args__ = (
        Index("ix_otp_email_created", "email", "created_at"),
        CheckConstraint("purpose IN ('signup', 'login')", name="purpose_valid"),
    )


class RefreshToken(Base):
    """Long-lived refresh token. Rotated on every refresh (one-time use)."""

    __tablename__ = "refresh_tokens"

    id: Mapped[uuid_pk]
    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    token_hash: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)
    device_id: Mapped[str | None] = mapped_column(String(128))
    user_agent: Mapped[str | None] = mapped_column(String(255))
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[created_at]

    user: Mapped["User"] = relationship(back_populates="refresh_tokens")

    __table_args__ = (
        Index("ix_refresh_user_active", "user_id", "revoked_at"),
    )


# ─── Playbooks ───────────────────────────────────────────────────────


class Playbook(Base):
    """Doc-grounded action recipe per (app_package, intent, app_version).

    Generated by the playbook ingestor (see services/playbook_ingestor.py)
    from the app's official user guide. Cached forever; updated when an
    app version changes the UI flow.
    """

    __tablename__ = "playbooks"

    id: Mapped[uuid_pk]
    app_package: Mapped[str] = mapped_column(String(255), nullable=False)
    app_name: Mapped[str] = mapped_column(String(100), nullable=False)
    app_version: Mapped[str | None] = mapped_column(String(32))
    intent: Mapped[str] = mapped_column(String(64), nullable=False)
    steps_json: Mapped[dict] = mapped_column(JSONB, nullable=False)
    source_doc_url: Mapped[str | None] = mapped_column(Text)
    reliability_score: Mapped[float] = mapped_column(
        Numeric(4, 3), default=0.0, nullable=False
    )
    popularity: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    is_payment_app: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[created_at]
    updated_at: Mapped[updated_at]

    __table_args__ = (
        UniqueConstraint(
            "app_package", "intent", "app_version",
            name="uq_playbooks_app_intent_version",
        ),
        CheckConstraint(
            "reliability_score >= 0 AND reliability_score <= 1",
            name="reliability_in_range",
        ),
        Index("ix_playbooks_popularity", "popularity"),
    )


# ─── Per-user app grants (allowlist) ─────────────────────────────────


class UserAppGrant(Base):
    """User has explicitly authorized Sahay to control this app."""

    __tablename__ = "user_app_grants"

    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    app_package: Mapped[str] = mapped_column(String(255), primary_key=True)
    granted_at: Mapped[created_at]
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    user: Mapped["User"] = relationship(back_populates="app_grants")


# ─── Action logs (privacy-clean: metadata only) ──────────────────────


class ActionLog(Base):
    """Per-action telemetry. NO message content, NO contact data — metadata only.

    Used for: usage metering, reliability scoring, debugging, billing.
    """

    __tablename__ = "action_logs"

    id: Mapped[uuid_pk]
    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    app_package: Mapped[str] = mapped_column(String(255), nullable=False)
    intent: Mapped[str] = mapped_column(String(64), nullable=False)
    status: Mapped[str] = mapped_column(String(16), nullable=False)
    duration_ms: Mapped[int | None] = mapped_column(Integer)
    tokens_used: Mapped[int | None] = mapped_column(Integer)
    cost_inr_paise: Mapped[int | None] = mapped_column(Integer)
    user_aborted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    failure_reason: Mapped[str | None] = mapped_column(String(255))
    model_used: Mapped[str | None] = mapped_column(String(64))
    created_at: Mapped[created_at]

    user: Mapped["User"] = relationship(back_populates="action_logs")

    __table_args__ = (
        Index("ix_action_logs_user_created", "user_id", "created_at"),
        Index("ix_action_logs_app_intent", "app_package", "intent"),
        CheckConstraint(
            "status IN ('success', 'failed', 'aborted', 'needs_confirm')",
            name="status_valid",
        ),
    )


# ─── Usage meters (Claude-style daily/weekly/monthly) ────────────────


class UsagePeriod(Base):
    """Pre-aggregated usage per user per period type. Updated atomically."""

    __tablename__ = "usage_periods"

    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    period_type: Mapped[str] = mapped_column(String(8), primary_key=True)
    period_start: Mapped[date] = mapped_column(Date, primary_key=True)
    action_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    tokens_used: Mapped[int] = mapped_column(BigInteger, default=0, nullable=False)
    cost_inr_paise: Mapped[int] = mapped_column(BigInteger, default=0, nullable=False)
    image_gens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    __table_args__ = (
        CheckConstraint(
            "period_type IN ('day', 'week', 'month')", name="period_type_valid"
        ),
    )


# ─── Files (R2-backed) ──────────────────────────────────────────────


class File(Base):
    """User-owned files (uploaded, generated, edited).

    Storage: Cloudflare R2 keyed by `r2_key`. Files are private by default;
    public access via signed URLs only.
    """

    __tablename__ = "files"

    id: Mapped[uuid_pk]
    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    folder: Mapped[str] = mapped_column(String(255), default="/", nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    mime_type: Mapped[str] = mapped_column(String(100), nullable=False)
    size_bytes: Mapped[int | None] = mapped_column(BigInteger)
    r2_key: Mapped[str] = mapped_column(String(512), unique=True, nullable=False)
    parent_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("files.id", ondelete="SET NULL")
    )
    source: Mapped[str] = mapped_column(String(16), default="upload", nullable=False)
    created_at: Mapped[created_at]

    user: Mapped["User"] = relationship(back_populates="files")

    __table_args__ = (
        Index("ix_files_user_folder", "user_id", "folder"),
        CheckConstraint(
            "source IN ('upload', 'generated', 'edited')", name="source_valid"
        ),
    )


# ─── Billing ─────────────────────────────────────────────────────────


class Subscription(Base):
    """Razorpay subscription state. One per user."""

    __tablename__ = "subscriptions"

    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    tier: Mapped[str] = mapped_column(String(16), nullable=False)
    razorpay_sub_id: Mapped[str | None] = mapped_column(String(64), unique=True)
    razorpay_customer_id: Mapped[str | None] = mapped_column(String(64))
    status: Mapped[str] = mapped_column(String(16), nullable=False)
    current_period_end: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )
    created_at: Mapped[created_at]
    updated_at: Mapped[updated_at]

    user: Mapped["User"] = relationship(back_populates="subscription")

    __table_args__ = (
        CheckConstraint(
            "status IN ('active', 'grace', 'cancelled', 'expired', 'pending')",
            name="status_valid",
        ),
    )


class UserMemory(Base):
    """Long-term per-user facts the agent has learnt and can recall.

    Lifecycle:
      • Agent writes with tool=`remember(key, value, category, importance)`.
      • Every agent turn's system prompt gets the top-K most-relevant
        memories pre-loaded (relevance = importance * recency decay).
      • Agent can `forget(key)` when a fact is obsolete.
      • Nightly compressor (Opus batch) dedupes + consolidates.

    Keys are slugified ("bosses-name", "preferred-voice-locale", …) so
    the model can reference them stably across sessions.
    """

    __tablename__ = "user_memory"

    id: Mapped[uuid_pk]
    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True,
    )
    key: Mapped[str] = mapped_column(String(128), nullable=False)
    value: Mapped[str] = mapped_column(Text, nullable=False)
    # Free-form category: "people" | "preferences" | "schedule" | "facts" | "habits"
    category: Mapped[str] = mapped_column(String(32), nullable=False, default="facts")
    # 1..10; higher = injected first when trimming to token budget.
    importance: Mapped[int] = mapped_column(Integer, nullable=False, default=5)
    # Soft signal — updated on read so stale memories fade from top-K.
    last_accessed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False,
    )
    # Source of truth: who set this — "agent" | "user" | "system".
    source: Mapped[str] = mapped_column(String(16), nullable=False, default="agent")

    created_at: Mapped[created_at]
    updated_at: Mapped[updated_at]

    __table_args__ = (
        UniqueConstraint("user_id", "key", name="uq_user_memory_user_key"),
        Index("ix_user_memory_user_importance", "user_id", "importance"),
        Index("ix_user_memory_user_last_accessed", "user_id", "last_accessed_at"),
        CheckConstraint(
            "importance BETWEEN 1 AND 10",
            name="ck_user_memory_importance_range",
        ),
    )


